function switchLanguage(lang) {
  const elements = document.querySelectorAll("[id]");
  elements.forEach(el => {
    const key = el.id;
    if (translations[lang][key]) {
      el.textContent = translations[lang][key];
    }
  });

  // Keep contact text with link
  const contactEl = document.getElementById("contact-text");
  contactEl.innerHTML = translations[lang]["contact-text"] +
    '<a href="mailto:asko.kiiskinen@kolumbus.fi">asko.kiiskinen@kolumbus.fi</a>';

  // Highlight active language
  document.getElementById("lang-en").classList.remove("active");
  document.getElementById("lang-fi").classList.remove("active");
  document.getElementById("lang-" + lang).classList.add("active");
}

// Default: English
document.getElementById("lang-en").classList.add("active");

document.getElementById("lang-en").addEventListener("click", () => switchLanguage("en"));
document.getElementById("lang-fi").addEventListener("click", () => switchLanguage("fi"));

